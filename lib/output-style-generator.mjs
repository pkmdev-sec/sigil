#!/usr/bin/env node
// prompt-studio: Output Style Generator (Innovation 7)
// Converts prompt-studio templates to/from Claude Code output styles
// Output styles live in ~/.claude/output-styles/ as markdown files

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'fs';
import { join, basename, extname } from 'path';
import { homedir } from 'os';

const OUTPUT_STYLES_DIR = process.env.SIGIL_OUTPUT_STYLES_DIR || join(homedir(), '.claude', 'output-styles');

// ─── Frontmatter Parsing ────────────────────────────────────────

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) return { metadata: {}, body: content.trim() };

  const meta = {};
  for (const line of match[1].split('\n')) {
    const idx = line.indexOf(':');
    if (idx > 0) {
      const key = line.slice(0, idx).trim();
      const val = line.slice(idx + 1).trim();
      meta[key] = val;
    }
  }
  return { metadata: meta, body: match[2].trim() };
}

function buildFrontmatter(metadata) {
  const lines = ['---'];
  for (const [key, val] of Object.entries(metadata)) {
    lines.push(`${key}: ${val}`);
  }
  lines.push('---');
  return lines.join('\n');
}

// ─── Template → Output Style Conversion ─────────────────────────

function templateToOutputStyle(templateBody, templateMeta) {
  // Claude output styles are markdown files with style instructions.
  // We convert the template's directives into output style format.
  const lines = [];

  const name = templateMeta.name || 'Custom Style';
  lines.push(`# ${name} Output Style`);
  lines.push('');
  lines.push(`> Generated by prompt-studio from template: ${templateMeta.name || 'unknown'}`);
  lines.push(`> Category: ${templateMeta.category || 'general'}`);
  lines.push('');

  // Extract sections from template body and rewrite as style directives
  const sections = parseTemplateSections(templateBody);

  for (const section of sections) {
    if (section.heading) {
      lines.push(section.heading);
    }
    if (section.content) {
      // Convert imperative instructions into style directives
      lines.push(section.content);
    }
    lines.push('');
  }

  return lines.join('\n').trim() + '\n';
}

function parseTemplateSections(body) {
  const sections = [];
  let currentHeading = '';
  let currentLines = [];

  for (const line of body.split('\n')) {
    if (/^#{1,3}\s/.test(line)) {
      if (currentHeading || currentLines.length > 0) {
        sections.push({
          heading: currentHeading,
          content: currentLines.join('\n').trim()
        });
      }
      currentHeading = line.trim();
      currentLines = [];
    } else {
      currentLines.push(line);
    }
  }

  if (currentHeading || currentLines.length > 0) {
    sections.push({
      heading: currentHeading,
      content: currentLines.join('\n').trim()
    });
  }

  return sections;
}

// ─── Output Style → Template Conversion ─────────────────────────

function outputStyleToTemplate(styleContent) {
  // Strip the "Generated by prompt-studio" header if present
  let body = styleContent;

  // Try to extract a name from the first heading
  const nameMatch = body.match(/^#\s+(.+?)(?:\s+Output Style)?\s*$/m);
  const name = nameMatch ? nameMatch[1].replace(/\s+Output Style$/, '') : 'Imported Style';

  // Remove the generated-by blockquote lines
  body = body.replace(/^>\s+Generated by prompt-studio.*\n/gm, '');
  body = body.replace(/^>\s+Category:.*\n/gm, '');
  body = body.trim();

  const metadata = {
    name,
    description: `Imported from output style: ${name}`,
    category: 'imported',
    author: 'prompt-studio',
    version: '1.0.0',
    tags: 'imported, output-style',
    use_with: '--append-system-prompt'
  };

  return buildFrontmatter(metadata) + '\n\n' + body + '\n';
}

// ─── Public API ─────────────────────────────────────────────────

/**
 * Generate a Claude Code output style from a prompt-studio template file.
 * Converts template format to output style format suitable for ~/.claude/output-styles/.
 * @param {string} templatePath - Path to the template .md file
 * @param {string} styleName - Name for the output style file (without .md extension)
 * @returns {{ styleName: string, content: string, path: string }} Output style metadata and content
 * @example
 * const style = generateOutputStyle('./templates/security-audit.md', 'security-style');
 * console.log(`Generated style: ${style.styleName}`);
 * console.log(`Will be saved to: ${style.path}`);
 */
export function generateOutputStyle(templatePath, styleName) {
  try {
    if (!templatePath || typeof templatePath !== 'string') {
      throw new Error('templatePath must be a non-empty string');
    }

    const raw = readFileSync(templatePath, 'utf-8');
    const { metadata, body } = parseFrontmatter(raw);

    const effectiveName = styleName || (metadata.name || basename(templatePath, '.md'))
      .toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');

    const content = templateToOutputStyle(body, metadata);
    const destPath = join(OUTPUT_STYLES_DIR, `${effectiveName}.md`);

    return { styleName: effectiveName, content, path: destPath };
  } catch (error) {
    throw new Error(`generateOutputStyle failed: ${error.message}`);
  }
}

/**
 * Install an output style by writing it to ~/.claude/output-styles/ directory.
 * Makes the style available for use with Claude Code's --output-style flag.
 * @param {string} styleName - Name for the file (without .md extension)
 * @param {string} content - Markdown content of the style
 * @returns {{ path: string, installed: boolean }} Installation result with file path
 * @example
 * const content = "# Concise Style\n\nBe direct and to the point.";
 * const result = installOutputStyle('concise', content);
 * console.log(`Installed: ${result.installed} at ${result.path}`);
 * // Now use with: claude --output-style concise "Your task"
 */
export function installOutputStyle(styleName, content) {
  try {
    if (!styleName || typeof styleName !== 'string') {
      throw new Error('styleName must be a non-empty string');
    }
    if (!content || typeof content !== 'string') {
      throw new Error('content must be a non-empty string');
    }

    if (!existsSync(OUTPUT_STYLES_DIR)) {
      mkdirSync(OUTPUT_STYLES_DIR, { recursive: true });
    }

    const filePath = join(OUTPUT_STYLES_DIR, `${styleName}.md`);
    writeFileSync(filePath, content, 'utf-8');

    return { path: filePath, installed: true };
  } catch (error) {
    throw new Error(`installOutputStyle failed: ${error.message}`);
  }
}

/**
 * List all installed output styles in ~/.claude/output-styles/ directory.
 * @returns {Array<{ name: string, path: string, size: number }>} Array of installed style metadata
 * @example
 * const styles = listInstalledStyles();
 * styles.forEach(s => {
 *   console.log(`${s.name}: ${s.size} bytes at ${s.path}`);
 * });
 */
export function listInstalledStyles() {
  try {
    if (!existsSync(OUTPUT_STYLES_DIR)) {
      return [];
    }

    const files = readdirSync(OUTPUT_STYLES_DIR).filter(f => extname(f) === '.md');

    return files.map(f => {
      const fullPath = join(OUTPUT_STYLES_DIR, f);
      const content = readFileSync(fullPath, 'utf-8');
      return {
        name: basename(f, '.md'),
        path: fullPath,
        size: content.length
      };
    });
  } catch (error) {
    throw new Error(`listInstalledStyles failed: ${error.message}`);
  }
}

/**
 * Import a Claude Code output style and convert it back to a prompt-studio template format.
 * Allows reusing output styles as prompt-studio templates.
 * @param {string} stylePath - Path to the output style .md file
 * @returns {{ templateContent: string, name: string }} Template content with frontmatter and extracted name
 * @example
 * const imported = importOutputStyle('~/.claude/output-styles/concise.md');
 * console.log(`Template name: ${imported.name}`);
 * // imported.templateContent has YAML frontmatter and can be saved as .md
 */
export function importOutputStyle(stylePath) {
  try {
    if (!stylePath || typeof stylePath !== 'string') {
      throw new Error('stylePath must be a non-empty string');
    }

    const content = readFileSync(stylePath, 'utf-8');
    const templateContent = outputStyleToTemplate(content);

    const nameMatch = templateContent.match(/^name:\s*(.+)$/m);
    const name = nameMatch ? nameMatch[1] : 'imported-style';

    return { templateContent, name };
  } catch (error) {
    throw new Error(`importOutputStyle failed: ${error.message}`);
  }
}
